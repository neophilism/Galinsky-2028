import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {renderPage,root} from '../scripts/public-renderer.mjs';
import {join} from 'node:path';

test('hero flag assembles from moving colliding particles and has 50 dot-star clusters',()=>{
  const html=renderPage('index');
  const motion=readFileSync(join(root,'apps/web/public/assets/motion.js'),'utf8');
  assert(html.includes('class="flag-canvas"'));
  assert(html.includes('/assets/motion.js'));
  assert(!html.includes('motion-toggle'));
  assert(!html.includes('Pause animation'));
  assert(!motion.includes("getElementById('motion-toggle')"));
  assert(motion.includes('prefers-reduced-motion: reduce'));
  assert(motion.includes("const count = row % 2 === 0 ? 6 : 5"));
  assert(motion.includes('for (let row = 0; row < 9; row++)'));
  assert(motion.includes("addParticle(u + Math.cos(angle)"));
  assert(motion.includes("'#ffffff'"));
  assert(motion.includes("const buckets = new Map()"));
  assert(motion.includes('const WANDER_SECONDS'));
  assert(motion.includes('const FORM_SECONDS'));
});
test('volunteer landing provides functioning preview with no dead portal links',()=>{
  const html=renderPage('volunteer');
  const js=readFileSync(join(root,'apps/web/public/assets/volunteer-preview.js'),'utf8');
  assert(html.includes('id="preview-workspace"'));
  assert(html.includes('/assets/volunteer-preview.js'));
  assert(html.includes('/assets/volunteer-preview.css'));
  assert(html.includes('href="#preview-workspace"'));
  assert(html.includes('id="preview-plan-text"'));
  assert(html.includes('id="preview-download"'));
  assert(html.includes('data-preview-task="issues"'));
  assert(html.includes('id="preview-role-select"'));
  assert.equal((html.match(/<option value="(?:0[2-9]|1[0-3])">/g)||[]).length,12);
  assert(!html.includes('href="/volunteer/#join"'));
  assert(!html.includes('href="{{PORTAL}}'));
  assert(js.includes('localStorage'));
  assert(js.includes('URL.createObjectURL'));
  assert(!js.includes('fetch('),'the preview must not send private draft content to APIs');
  assert(js.includes('PREPARATION ONLY'));
  assert(!js.includes('mailto:'));
});
